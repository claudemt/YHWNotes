from pathlib import Path
import json

BASE = Path(__file__).resolve().parents[1]
texts = {}
changes = []

def edit(name, old, new):
    p = BASE / name
    s = texts.setdefault(p, p.read_text(encoding="utf-8"))
    if s.count(old) != 1:
        raise ValueError(f"Expected unique passage in {name}: {old[:90]!r}; got {s.count(old)}")
    texts[p] = s.replace(old, new)
    changes.append({"file": name, "before": old, "after": new})

def region(name, start, end, new):
    p = BASE / name
    s = texts.setdefault(p, p.read_text(encoding="utf-8"))
    a, b = s.index(start), s.index(end, s.index(start))
    edit(name, s[a:b], new)

